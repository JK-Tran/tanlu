class _SeedStudent {
  const _SeedStudent({
    required this.id,
    required this.classId,
    required this.classNum,
    required this.index,
    required this.fullName,
    required this.nickname,
    required this.gender,
    required this.dob,
    required this.fatherName,
    required this.motherName,
    required this.fatherPhone,
    required this.motherPhone,
    required this.fatherDob,
    required this.motherDob,
    required this.address,
    this.diagnosis = '',
    this.allergies = '',
    this.developmentAgeMonth = 24,
  });

  final String id;
  final String classId;
  final int classNum;
  final int index;
  final String fullName;
  final String nickname;
  final String gender;
  final String dob;
  final String fatherName;
  final String motherName;
  final String fatherPhone;
  final String motherPhone;
  final String fatherDob;
  final String motherDob;
  final String address;
  final String diagnosis;
  final String allergies;
  final int developmentAgeMonth;

  String get studentCode => 'HS-C$classNum-${index.toString().padLeft(3, '0')}';

  String get avatarUrl =>
      gender == 'Nam' ? StudentSeedAvatars.boy : StudentSeedAvatars.girl;

  Map<String, dynamic> toFirestore() {
    return {
      'classId': classId,
      'fullName': fullName,
      'nickname': nickname,
      'gender': gender,
      'dob': dob,
      'dateOfBirth': dob,
      'avatarUrl': avatarUrl,
      'studentCode': studentCode,
      'status': 'active',
      'address': address,
      'birthHistory': '',
      'bloodType': '',
      'diagnosis': diagnosis,
      'allergies': allergies,
      'currentMedications': '',
      'likes': '',
      'dislikesOrTriggers': '',
      'selfCareSkills': '',
      'initialReason': '',
      'diagnosisSummary': diagnosis,
      'developmentAgeMonth': developmentAgeMonth,
      'supportLevel': '',
      'parentUserId': '',
      'contacts': [
        {
          'name': fatherName,
          'relationship': 'Bố',
          'phone': fatherPhone,
          'dob': fatherDob,
          'isPrimary': true,
        },
        {
          'name': motherName,
          'relationship': 'Mẹ',
          'phone': motherPhone,
          'dob': motherDob,
          'isPrimary': false,
        },
      ],
      'createdAt': FieldValue.serverTimestamp(),
      'updatedAt': FieldValue.serverTimestamp(),
    };
  }
}

