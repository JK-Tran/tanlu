/// Ghi 20 học sinh demo (10 × class-1, 10 × class-2) lên Firestore.
Future<void> seedDemoStudentsToFirestore() async {
  final firestore = FirebaseFirestore.instance;
  final batch = firestore.batch();
  final all = [..._class1Students, ..._class2Students];

  for (final student in all) {
    batch.set(
      firestore.collection('students').doc(student.id),
      student.toFirestore(),
    );
  }

  await batch.commit();
}

int get demoStudentSeedCount => _class1Students.length + _class2Students.length;
